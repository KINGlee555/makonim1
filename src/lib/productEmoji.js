export function getProductEmoji(name, category) {
  if (name) {
    const lower = name.toLowerCase();
    for (const rule of EMOJI_RULES) {
      if (rule.keys.some(k => lower.includes(k))) return rule.emoji;
    }
  }
  return CATEGORY_FALLBACK[category] || "🛒";
}