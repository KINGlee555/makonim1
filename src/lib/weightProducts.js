// נתחים טריים שנשקלים בדלפק הבשר והדגים
const FRESH_COUNTER = [
  "אנטריקוט", "פילה", "כרעיי", "פרגית", "סטייק", "צלעות", "אונטריב", "שפונדרה",
  "בשר טחון טרי", "דג טרי",
];

// אריזה סגורה — יש משקל או נפח בשם, ולכן קונים אותה ביחידות
const PACKAGE_HINT = /\d\s*(גר|גרם|ק"ג|קילו|קג|מ"ל|מל|ליטר|ל|יח|יח')/;

// מוצר מעובד או קפוא — לא נשקל בדלפק
const PROCESSED = [
  "קפוא", "שניצל", "נקניק", "המבורגר", "קציצ", "מעובד", "ממרח", "שימור", "משומר",
  "רוטב", "מיץ", "מטוגן", "אפוי", "ממולא", "בצק", "מרק", "סלט מוכן", "חטיף", "יבש",
];

// ההשוואה מתחילה בתחילת מילה, כדי ש"משומר" לא ייחשב בטעות ל"שום"
const startsWord = (name, keyword) => new RegExp(`(^|\\s)${keyword}`).test(name);

export function isWeightSold(product) {
  if (!product) return false;
  if (product.weighted) return true;
  const name = String(product.name || "").trim();
  if (!name) return false;
  if (PACKAGE_HINT.test(name)) return false;
  if (PROCESSED.some(word => name.includes(word))) return false;
  if (PRODUCE.some(keyword => startsWord(name, keyword))) return true;
  const category = String(product.category || "");
  if (category === "בשר ודגים" && FRESH_COUNTER.some(keyword => startsWord(name, keyword))) return true;
  return false;
}